#!/bin/sh
# Writes the Homebrew formula for a published release into the tap cj-ways/homebrew-driftmark,
# from the release's SHA256SUMS. Run it after each release, with a gh login that can write the tap.
#   scripts/update-tap.sh 0.1.0                         write the formula into the tap
#   scripts/update-tap.sh 0.1.0 --print                 only print it
#   scripts/update-tap.sh 0.1.0 --print --sums <file>   print it from a local SHA256SUMS (a test)
set -eu
usage="usage: scripts/update-tap.sh <version> [--print] [--sums <file>]"
v=${1:?$usage}
v=${v#v}
shift
print=
sums_file=
while [ $# -gt 0 ]; do
  case "$1" in
    --print) print=1 ;;
    --sums)
      sums_file=${2:?$usage}
      shift
      ;;
    *)
      echo "$usage" >&2
      exit 2
      ;;
  esac
  shift
done
repo=cj-ways/driftmark
tap=cj-ways/homebrew-driftmark
base=https://github.com/$repo/releases/download/v$v
if [ -n "$sums_file" ]; then
  sums=$(cat "$sums_file")
else
  sums=$(gh release download "v$v" -R "$repo" -p SHA256SUMS -O -)
fi

sha() {
  s=$(printf '%s\n' "$sums" | awk -v f="driftmark-$1.tar.gz" '$2 == f || $2 == "*" f { print $1 }')
  [ -n "$s" ] || {
    echo "no checksum for driftmark-$1.tar.gz in v$v" >&2
    exit 1
  }
  printf '%s' "$s"
}
# Each checksum is read before the formula is written, so a missing one stops the script
# (a failure inside the formula's $(...) would only end a subshell).
mac_arm=$(sha aarch64-apple-darwin)
mac_intel=$(sha x86_64-apple-darwin)
linux_arm=$(sha aarch64-unknown-linux-gnu)
linux_intel=$(sha x86_64-unknown-linux-gnu)

formula=$(cat <<EOF
# Generated by scripts/update-tap.sh in $repo; edits here are overwritten.
class Driftmark < Formula
  desc "Review what AI agents changed in Markdown docs, ranked by meaning"
  homepage "https://github.com/$repo"
  version "$v"
  license any_of: ["MIT", "Apache-2.0"]

  on_macos do
    on_arm do
      url "$base/driftmark-aarch64-apple-darwin.tar.gz"
      sha256 "$mac_arm"
    end
    on_intel do
      url "$base/driftmark-x86_64-apple-darwin.tar.gz"
      sha256 "$mac_intel"
    end
  end

  # Built against glibc 2.28: it runs where the system's glibc is 2.28 or newer.
  on_linux do
    on_arm do
      url "$base/driftmark-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "$linux_arm"
    end
    on_intel do
      url "$base/driftmark-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "$linux_intel"
    end
  end

  def install
    bin.install "driftmark"
    doc.install "THIRD-PARTY-NOTICES"
  end

  test do
    assert_match "driftmark #{version}", shell_output("#{bin}/driftmark --version")
  end
end
EOF
)

if [ -n "$print" ]; then
  printf '%s\n' "$formula"
  exit 0
fi
old=$(gh api "repos/$tap/contents/Formula/driftmark.rb" --jq .sha 2>/dev/null) || old= # none yet
gh api -X PUT "repos/$tap/contents/Formula/driftmark.rb" --silent \
  -f message="feat: driftmark $v" \
  -f content="$(printf '%s\n' "$formula" | base64 | tr -d '\n')" \
  ${old:+-f sha="$old"}
echo "tap updated: brew install cj-ways/driftmark/driftmark  (or: brew upgrade driftmark)"
